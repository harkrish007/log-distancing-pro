package com.shopping.service;

import jakarta.annotation.Resource;
import jakarta.servlet.ServletContextEvent;
import jakarta.servlet.ServletContextListener;
import jakarta.servlet.annotation.WebListener;
import org.mindrot.jbcrypt.BCrypt;
import javax.sql.DataSource;
import java.sql.*;

/**
 * DbSeeder — seeds the H2 database at application startup.
 *
 * Scale: 1,000 users + 1,000 products (research baseline for log-distancing
 * performance analysis).  All inserts use JDBC batch mode to minimise per-row
 * round-trip overhead; timing is logged at nanosecond resolution so
 * messages.log captures the data needed for startup performance analysis.
 *
 * Log markers emitted (searchable in messages.log):
 *   [SEED] Schema ready
 *   [SEED] Users   start  | elapsed_ms=<ms>
 *   [SEED] Users   done   | count=1002 elapsed_ms=<ms>
 *   [SEED] Products start | elapsed_ms=<ms>
 *   [SEED] Products done  | count=1000 elapsed_ms=<ms>
 *   [SEED] Total seeding  | elapsed_ms=<ms>
 */
@WebListener
public class DbSeeder implements ServletContextListener {

    private static final int USER_COUNT    = 1_000;
    private static final int PRODUCT_COUNT = 1_000;
    private static final int BATCH_SIZE    = 100;

    // Product catalogue — 10 categories × 100 items each = 1 000 products
    private static final String[] CATEGORIES = {
        "Laptop", "Headphones", "Smartphone", "Keyboard", "Monitor",
        "Tablet", "Smartwatch", "Camera", "Speaker", "Printer"
    };
    private static final double[] BASE_PRICES = {
        1299.99, 299.99, 899.99, 119.99, 449.99,
         649.99, 399.99, 749.99, 199.99,  89.99
    };
    private static final int[] BASE_INVENTORY = {
        15, 25, 10, 30, 8,
        20, 35, 12, 40, 50
    };

    @Resource(lookup = "jdbc/ShoppingCartDS")
    private DataSource ds;

    @Override
    public void contextInitialized(ServletContextEvent sce) {
        long t0 = System.nanoTime();
        try (Connection con = ds.getConnection()) {
            con.setAutoCommit(false);
            createSchema(con);
            seedUsers(con, t0);
            seedProducts(con, t0);
            con.setAutoCommit(true);
        } catch (Exception e) {
            System.err.println("DbSeeder error: " + e.getMessage());
            e.printStackTrace();
        }
        long totalMs = (System.nanoTime() - t0) / 1_000_000;
        System.out.println("[SEED] Total seeding  | elapsed_ms=" + totalMs);
    }

    // ── schema ────────────────────────────────────────────────────────────────

    private void createSchema(Connection con) throws SQLException {
        try (Statement st = con.createStatement()) {
            st.execute(
                "CREATE TABLE IF NOT EXISTS USERS (" +
                "  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "  USERNAME VARCHAR(50) NOT NULL UNIQUE," +
                "  PASSWORD VARCHAR(100) NOT NULL," +
                "  ROLE VARCHAR(20) NOT NULL" +
                ")"
            );
            st.execute(
                "CREATE TABLE IF NOT EXISTS PRODUCTS (" +
                "  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "  NAME VARCHAR(100) NOT NULL," +
                "  DESCRIPTION VARCHAR(500)," +
                "  PRICE DOUBLE NOT NULL," +
                "  IMAGEURL VARCHAR(255)," +
                "  INVENTORY INT NOT NULL" +
                ")"
            );
            st.execute(
                "CREATE TABLE IF NOT EXISTS CART_ITEMS (" +
                "  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "  USER_ID BIGINT NOT NULL," +
                "  PRODUCT_ID BIGINT NOT NULL," +
                "  QUANTITY INT NOT NULL," +
                "  CONSTRAINT UQ_CART UNIQUE (USER_ID, PRODUCT_ID)," +
                "  CONSTRAINT FK_CART_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)," +
                "  CONSTRAINT FK_CART_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID)" +
                ")"
            );
            con.commit();
            System.out.println("[SEED] Schema ready");
        }
    }

    // ── users ─────────────────────────────────────────────────────────────────

    private void seedUsers(Connection con, long t0) throws SQLException {
        try (PreparedStatement count = con.prepareStatement("SELECT COUNT(*) FROM USERS")) {
            ResultSet rs = count.executeQuery();
            rs.next();
            if (rs.getLong(1) > 0) {
                System.out.println("[SEED] Users   skip  | already seeded");
                return;
            }
        }

        long tStart = System.nanoTime();
        System.out.println("[SEED] Users   start | elapsed_ms=" + (tStart - t0) / 1_000_000);

        // Pre-hash two canonical passwords once (BCrypt is expensive — reuse for bulk)
        String userHash  = BCrypt.hashpw("password123", BCrypt.gensalt());
        String adminHash = BCrypt.hashpw("admin123",    BCrypt.gensalt());

        try (PreparedStatement ps = con.prepareStatement(
                "INSERT INTO USERS (USERNAME, PASSWORD, ROLE) VALUES (?, ?, ?)")) {

            // Always insert the canonical accounts first
            ps.setString(1, "testuser"); ps.setString(2, userHash);  ps.setString(3, "USER");  ps.addBatch();
            ps.setString(1, "admin");    ps.setString(2, adminHash); ps.setString(3, "ADMIN"); ps.addBatch();

            // Bulk 1 000 generated users (user_0001 … user_1000)
            for (int i = 1; i <= USER_COUNT; i++) {
                ps.setString(1, String.format("user_%04d", i));
                ps.setString(2, userHash);
                ps.setString(3, "USER");
                ps.addBatch();
                if (i % BATCH_SIZE == 0) {
                    ps.executeBatch();
                    con.commit();
                }
            }
            ps.executeBatch();
            con.commit();
        }

        long tDone = System.nanoTime();
        System.out.println("[SEED] Users   done  | count=" + (USER_COUNT + 2) + " elapsed_ms=" + (tDone - tStart) / 1_000_000);
    }

    // ── products ──────────────────────────────────────────────────────────────

    private void seedProducts(Connection con, long t0) throws SQLException {
        try (PreparedStatement count = con.prepareStatement("SELECT COUNT(*) FROM PRODUCTS")) {
            ResultSet rs = count.executeQuery();
            rs.next();
            if (rs.getLong(1) > 0) {
                System.out.println("[SEED] Products skip  | already seeded");
                return;
            }
        }

        long tStart = System.nanoTime();
        System.out.println("[SEED] Products start| elapsed_ms=" + (tStart - t0) / 1_000_000);

        // 10 categories × 100 items = 1 000 products
        int itemsPerCategory = PRODUCT_COUNT / CATEGORIES.length;

        try (PreparedStatement ps = con.prepareStatement(
                "INSERT INTO PRODUCTS (NAME, DESCRIPTION, PRICE, IMAGEURL, INVENTORY) VALUES (?, ?, ?, ?, ?)")) {

            int batchCount = 0;
            for (int c = 0; c < CATEGORIES.length; c++) {
                String cat       = CATEGORIES[c];
                double basePrice = BASE_PRICES[c];
                int    baseInv   = BASE_INVENTORY[c];

                for (int i = 1; i <= itemsPerCategory; i++) {
                    String name  = String.format("%s Model-%03d", cat, i);
                    String desc  = String.format(
                            "%s series product #%d. Features include enhanced performance, " +
                            "long-lasting build quality, and competitive pricing.",
                            cat, i);
                    double price = Math.round((basePrice + (i * 0.99)) * 100.0) / 100.0;
                    String img   = "https://images.unsplash.com/photo-1496181130204?w=400";
                    int    inv   = Math.max(1, baseInv - (i % 10));

                    ps.setString(1, name);
                    ps.setString(2, desc);
                    ps.setDouble(3, price);
                    ps.setString(4, img);
                    ps.setInt(5, inv);
                    ps.addBatch();
                    batchCount++;

                    if (batchCount % BATCH_SIZE == 0) {
                        ps.executeBatch();
                        con.commit();
                    }
                }
            }
            ps.executeBatch();
            con.commit();
        }

        long tDone = System.nanoTime();
        System.out.println("[SEED] Products done | count=" + PRODUCT_COUNT + " elapsed_ms=" + (tDone - tStart) / 1_000_000);
    }
}
